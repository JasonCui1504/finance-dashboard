"use client";

import { useEffect, useRef, useState } from "react";
import type { InsightFacts } from "../../../lib/finance/insights";

type Status = "idle" | "loading" | "streaming" | "done" | "error";

// "- foo", "* foo", "• foo" and "1. foo" all become list items; anything else
// (a stray heading or preamble) is shown as a plain paragraph.
const BULLET = /^\s*(?:[-*•]|\d+[.)])\s+/;

function Inline({ text }: { text: string }) {
  // Render **bold** spans; everything else is plain text.
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return (
    <>
      {parts.map((p, i) =>
        p.startsWith("**") && p.endsWith("**") ? (
          <strong key={i} className="font-medium text-prose">
            {p.slice(2, -2)}
          </strong>
        ) : (
          <span key={i}>{p}</span>
        )
      )}
    </>
  );
}

export default function AiInsights({ facts }: { facts: InsightFacts }) {
  const [status, setStatus] = useState<Status>("idle");
  const [text, setText] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [model, setModel] = useState<string | null>(null);
  const abortRef = useRef<AbortController | null>(null);

  useEffect(() => () => abortRef.current?.abort(), []);

  async function generate() {
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;
    setText("");
    setError(null);
    setStatus("loading");
    try {
      const res = await fetch("/api/finance/insights", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(facts),
        signal: controller.signal,
      });
      if (!res.ok || !res.body) {
        const body = await res.json().catch(() => null);
        throw new Error(body?.error ?? `Request failed (${res.status})`);
      }
      setModel(res.headers.get("X-Model"));
      setStatus("streaming");
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        setText((t) => t + decoder.decode(value, { stream: true }));
      }
      setStatus("done");
    } catch (err) {
      if (controller.signal.aborted) {
        setStatus((s) => (s === "loading" ? "idle" : "done"));
        return;
      }
      setError(err instanceof Error ? err.message : String(err));
      setStatus("error");
    }
  }

  const busy = status === "loading" || status === "streaming";
  const lines = text.split("\n").filter((l) => l.trim());

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-wrap items-center gap-3">
        <button
          type="button"
          onClick={busy ? () => abortRef.current?.abort() : generate}
          className="rounded-md border border-line px-3 py-1.5 text-sm text-subtle transition-colors hover:border-accent hover:text-prose"
        >
          {busy ? "Stop" : status === "idle" ? "Generate insights" : "Regenerate"}
        </button>
        <span className="text-xs text-faint">
          {status === "loading"
            ? "Loading the model… the first run can take a few seconds."
            : `Runs locally${model ? ` on ${model}` : ""} via Ollama — totals only, nothing leaves this Mac.`}
        </span>
      </div>

      {error && (
        <p
          className="rounded-lg border px-4 py-3 text-sm text-subtle"
          style={{ borderColor: "#e6676755", background: "#e6676712" }}
        >
          {error}
        </p>
      )}

      {lines.length > 0 && (
        <ul className="flex flex-col gap-2.5 text-sm leading-relaxed text-subtle">
          {lines.map((line, i) =>
            BULLET.test(line) ? (
              <li key={i} className="flex gap-2.5">
                <span
                  className="mt-[0.55em] inline-block h-1.5 w-1.5 shrink-0 rounded-full bg-accent"
                  aria-hidden
                />
                <span>
                  <Inline text={line.replace(BULLET, "")} />
                </span>
              </li>
            ) : (
              <li key={i}>
                <Inline text={line} />
              </li>
            )
          )}
        </ul>
      )}

      {status === "done" && lines.length > 0 && (
        <p className="text-xs text-faint">
          Generated by a small local model from the figures above. It can misread
          numbers, so double-check before acting on anything.
        </p>
      )}
    </div>
  );
}
